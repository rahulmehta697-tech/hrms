#!/usr/bin/env node
// Licence tool for the vendor. Never ship the private key with the app.
//   node scripts/license.mjs keygen [--dir ./licence-keys]
//   node scripts/license.mjs issue --customer "Name" --employees 500 --expires 2027-10-31 [--grace 15] [--key ./licence-keys/licence-private.pem]
//   node scripts/license.mjs verify <key>
import { generateKeyPairSync, createPrivateKey, createPublicKey, sign, verify, randomBytes } from "crypto";
import fs from "fs";
import path from "path";

const args = process.argv.slice(2);
const cmd = args[0];
const opt = (k, d) => { const i = args.indexOf("--" + k); return i > 0 ? args[i + 1] : d; };
const PUB_FILE = path.join(process.cwd(), "src/lib/license-public.ts");

if (cmd === "keygen") {
  const dir = opt("dir", "./licence-keys");
  const priv = path.join(dir, "licence-private.pem");
  if (fs.existsSync(priv)) { console.error(`${priv} already exists. Keys are made once; delete it only if you mean to invalidate every licence you have issued.`); process.exit(1); }
  const { publicKey, privateKey } = generateKeyPairSync("ed25519");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(priv, privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
  const pub = publicKey.export({ type: "spki", format: "pem" });
  fs.writeFileSync(PUB_FILE, `/**\n * Public half of your licence-signing key. Generated by \`node scripts/license.mjs keygen\`.\n * Empty means no key has been generated yet: every deployment then runs in demo mode.\n */\nexport const LICENCE_PUBLIC_KEY = \`${pub}\`;\n`);
  console.log(`Private key saved to ${priv}  <- keep this safe and backed up; it is NOT in git.`);
  console.log(`Public key written to src/lib/license-public.ts  <- commit and push this file.`);
} else if (cmd === "issue") {
  const customer = opt("customer"), employees = Number(opt("employees", "0")), expires = opt("expires"), grace = Number(opt("grace", "15"));
  if (!customer || !/^\d{4}-\d{2}-\d{2}$/.test(expires || "")) { console.error('Usage: issue --customer "Name" --employees 500 --expires 2027-10-31 [--grace 15]'); process.exit(1); }
  const key = createPrivateKey(fs.readFileSync(opt("key", "./licence-keys/licence-private.pem")));
  const payload = { id: randomBytes(4).toString("hex"), c: customer, e: employees, x: expires, i: new Date().toISOString().slice(0, 10), g: grace };
  const body = Buffer.from(JSON.stringify(payload)).toString("base64url");
  const sig = sign(null, Buffer.from(body), key).toString("base64url");
  console.log(`HRMS1.${body}.${sig}`);
  console.error(`\nLicence ${payload.id}: ${customer}, ${employees || "unlimited"} employees, expires ${expires}, ${grace}-day grace.`);
} else if (cmd === "verify") {
  const k = (args[1] || "").trim();
  const m = /^HRMS1\.([A-Za-z0-9_-]+)\.([A-Za-z0-9_-]+)$/.exec(k);
  const src = fs.readFileSync(PUB_FILE, "utf8"), pem = /LICENCE_PUBLIC_KEY = `([\s\S]*?)`/.exec(src)?.[1];
  if (!m || !pem?.trim()) { console.error("Bad key, or no public key generated yet."); process.exit(1); }
  const ok = verify(null, Buffer.from(m[1]), createPublicKey(pem), Buffer.from(m[2], "base64url"));
  console.log(ok ? "Genuine:" : "NOT genuine:", JSON.parse(Buffer.from(m[1], "base64url").toString()));
} else {
  console.log("Commands: keygen | issue | verify  (see the top of this file)");
}
